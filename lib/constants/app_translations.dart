  static String localizePlaceLabel(String raw, String Function(String key) tr) {
    final t = raw.trim();
    if (t.contains('地圖自選終點') ||
        t.contains('地图自选终点') ||
        t.toLowerCase().contains('custom end') ||
        t.toLowerCase().contains('fim personalizado')) {
      return tr('custom_end');
    }
    if (t.contains('地圖自選起點') ||
        t.contains('地图自选起点') ||
        t.toLowerCase().contains('custom start') ||
        t.toLowerCase().contains('início personalizado') ||
        t.toLowerCase().contains('inicio personalizado')) {
      return tr('custom_start');
    }
    if (t.contains('目前位置') ||
        t.contains('当前位置') ||
        t.toLowerCase().contains('current location') ||
        t.toLowerCase().contains('localização atual') ||
        t.toLowerCase().contains('localizacao atual')) {
      return tr('current_gps_location');
    }
    if (t.toLowerCase() == 'origin') return tr('map_start_name');
    if (t.toLowerCase() == 'destination') return tr('map_dest_name');
    return raw;
  }

  /// Known Chinese client/server error messages -> current language.
  static String localizeErrorMessage(String raw, String Function(String key) tr) {
    final s = raw.trim();
    if (s.contains('逾時') || s.contains('被阻擋')) return tr('err_server_blocked');
    if (s.contains('查無此路線') || s.contains('循環路線')) return tr('err_no_stops');
    if (s == '查詢失敗') return tr('err_query_failed');
    if (s.startsWith('查無路線')) return tr('err_no_stops');
    return raw;
  }

  static String localizeEtaStatus(String raw, String Function(String key) tr) {
    final s = raw.trim();
    if (s.isEmpty) return tr('no_eta');
    if (s == tr('no_eta') || s.contains('未有') || s.toLowerCase().contains('no eta') || s.toLowerCase().contains('sem eta')) {
      return tr('no_eta');
    }
    if (s == tr('conn_failed') || s.contains('連線失敗') || s.contains('连线失败')) {
      return tr('conn_failed');
    }
    if (s.contains('即將到站') ||
        s.contains('即将到站') ||
        s.contains('到站中') ||
        s.toLowerCase().contains('arriving') && s.toLowerCase().contains('soon')) {
      return tr('arriving_soon');
    }
    if (s.contains('不設服務') || s.contains('不设服务')) return tr('no_service_today');
    if (s.contains('尚未開始') || s.contains('尚未开始') || s.contains('未開始')) {
      return tr('service_not_started');
    }
    if (s.contains('服務已結束') || s.contains('服务已结束') || s.contains('收車')) {
      return tr('service_ended');
    }
    if (s.contains('可能已過站') ||
        s.contains('可能已过站') ||
        s.toLowerCase().contains('may have passed') ||
        s.contains('pode já ter passado')) {
      return tr('last_bus_maybe_passed');
    }
    if (s.contains('尾班車已過') || s.contains('尾班车已过')) return tr('last_bus_departed');
    if (s.contains('等候總站') || s.contains('等候总站')) return tr('waiting_at_terminal');
    if (s.contains('已到站')) return tr('arrived_at_stop');

    final stopsMins = RegExp(
      r'(?:尚有\s*)?(\d+)\s*(?:站).*(?:約|约)?\s*(\d+)\s*(?:分鐘|分钟)',
    ).firstMatch(s);
    if (stopsMins != null) {
      return tr('stops_away_mins')
          .replaceAll('@stops', stopsMins.group(1)!)
          .replaceAll('@mins', stopsMins.group(2)!);
    }
    final nextMins = RegExp(
      r'下站到達.*(?:約|约)?\s*(\d+)\s*(?:分鐘|分钟)',
    ).firstMatch(s);
    if (nextMins != null) {
      return tr('arriving_next_mins').replaceAll('@mins', nextMins.group(1)!);
    }
    if (s.contains('下站到達') || s.contains('下站到达')) return tr('arriving_next');
    final stopsOnly = RegExp(r'(?:尚有\s*)?(\d+)\s*站').firstMatch(s);
    if (stopsOnly != null) {
      return tr('stops_away').replaceAll('@stops', stopsOnly.group(1)!);
    }
    final mins = RegExp(
      r'(?:約|约|~)?\s*(\d+)\s*(?:分鐘|分钟|mins?|min)\b',
      caseSensitive: false,
    ).firstMatch(s);
    if (mins != null) {
      return tr('approx_mins').replaceAll('@mins', mins.group(1)!);
    }
    return s;
  }
